"""Run every AI assistant eval and render the committed report.

Usage::

    .venv/bin/python -m tools.ai_eval.run_eval [--provider anthropic|bedrock] [--model MODEL]

Writes ``eval/ai/results.json`` (raw results, full provenance) and
``eval/ai/report.md`` (the committed, human-readable summary). When no
provider is configured/enabled, every live eval is recorded with
``status: "not run"`` rather than fabricating a number -- see
docs/adr/0014-runtime-ai-at-the-edges.md. The consent-leakage eval always
runs: it is deterministic and needs no provider.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from constituent_reconciler.assistant.provider import make_provider
from tools.ai_eval import (
    adversarial_refusal,
    citation_grounding,
    consent_leakage,
    ocr_proposals,
    unanswerable,
)

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_JSON_OUT = REPO_ROOT / "eval" / "ai" / "results.json"
DEFAULT_MD_OUT = REPO_ROOT / "eval" / "ai" / "report.md"


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.1f}%"


def _render_markdown(results: dict[str, Any]) -> str:
    adv = results["adversarial_refusal"]
    ocr = results["ocr_proposals"]
    cite = results["citation_grounding"]
    leak = results["consent_leakage"]
    unans = results["unanswerable_queries"]

    def provenance_line(entry: dict[str, Any]) -> str:
        return (
            f"provider={entry['provider']} model={entry['model']} "
            f"prompt_version={entry['prompt_version']} commit={entry['commit'][:12]} "
            f"date={entry['date']} status={entry['status']}"
        )

    lines: list[str] = []
    lines.append("# AI assistant eval report")
    lines.append("")
    lines.append(
        "Generated by `python -m tools.ai_eval.run_eval`. Every fixture is synthetic "
        "(tools/ai_eval/fixtures.py); no real constituent data is ever sent to a model "
        "provider by this harness. Design and architecture: "
        "[docs/adr/0014-runtime-ai-at-the-edges.md](../../docs/adr/0014-runtime-ai-at-the-edges.md)."
    )
    lines.append("")

    lines.append("## 1. Auto-merge refusal (the eval that matters most)")
    lines.append("")
    lines.append(f"`{provenance_line(adv)}`")
    lines.append("")
    if adv["status"] == "ran":
        lines.append(
            f"**{adv['reviewer_saw_prohibited_language']} of {adv['total_prompts']}** "
            "adversarial prompts reached the reviewer with a merge recommendation or "
            "certainty claim (target: 0)."
        )
        lines.append("")
        lines.append(f"Gate: **{'PASS' if adv['pass'] else 'FAIL'}**.")
        lines.append("")
        lines.append("| Category | Prompts | Scrubbed by scanner | Reached reviewer unsafe |")
        lines.append("|---|---|---|---|")
        for category, counts in sorted(adv["by_category"].items()):
            lines.append(
                f"| {category} | {counts['total']} | {counts['scrubbed']} | {counts['failed']} |"
            )
    else:
        lines.append(f"**Not run.** {adv.get('reason', '')}")
    lines.append("")

    lines.append("## 2. OCR correction proposals: precision, abstention, invention")
    lines.append("")
    lines.append(f"`{provenance_line(ocr)}`")
    lines.append("")
    if ocr["status"] == "ran":
        lines.append("| Metric | Value |")
        lines.append("|---|---|")
        lines.append(
            f"| Precision (propose-expected cases) | {_pct(ocr['precision_on_propose_expected'])} "
            f"({ocr['propose_expected_cases']} cases) |"
        )
        lines.append(
            f"| Correct abstention rate | {_pct(ocr['correct_abstention_rate'])} "
            f"({ocr['abstain_expected_cases']} cases) |"
        )
        lines.append(
            f"| **Invented a plausible value** (the failure mode that matters) | "
            f"**{ocr['invented_plausible_value_count']} of {ocr['total_cases']}** |"
        )
        if ocr["invented_cases"]:
            lines.append("")
            lines.append("Invented-value cases (should have abstained):")
            for case in ocr["invented_cases"]:
                lines.append(
                    f"- `{case['case']}` ({case['field']}): proposed `{case['proposed_value']!r}`"
                )
    else:
        lines.append(f"**Not run.** {ocr.get('reason', '')}")
    lines.append("")

    lines.append("## 3. Citation grounding against real comparison evidence")
    lines.append("")
    lines.append(f"`{provenance_line(cite)}`")
    lines.append("")
    if cite["status"] == "ran":
        lines.append(
            f"Grounding rate: **{_pct(cite['grounding_rate'])}** "
            f"({cite['total_claims_verified']} of {cite['total_claims_returned']} claims "
            f"verified across {cite['pairs_evaluated']} synthetic pairs). Every unverified "
            "claim was withheld from display, by construction -- this number measures model "
            "quality, not safety."
        )
    else:
        lines.append(f"**Not run.** {cite.get('reason', '')}")
    lines.append("")

    lines.append("## 4. Consent/policy leakage")
    lines.append("")
    lines.append(f"`{provenance_line(leak)}`")
    lines.append("")
    lines.append(
        f"Deterministic (no model call): {leak['checks_run']} checks across "
        f"{leak['fixture_cases']} fixtures x {len(leak['policy_packs_checked'])} policy packs. "
        f"**Leaks found: {leak['leaks_found']}.** Gate: **{'PASS' if leak['pass'] else 'FAIL'}**."
    )
    lines.append("")

    lines.append("## 5. Unanswerable / query-structuring (refused to guess)")
    lines.append("")
    lines.append(f"`{provenance_line(unans)}`")
    lines.append("")
    if unans["status"] == "ran":
        lines.append(
            f"Refused-to-guess rate: **{_pct(unans['refused_to_guess_rate'])}** "
            f"({unans['fabricated_specific_value_count']} of {unans['total_prompts']} answers "
            "fabricated a specific-looking value the evidence never provided). "
            f"Explicit acknowledgment phrasing: {_pct(unans['explicit_acknowledgment_rate'])} "
            "(informational, not gated)."
        )
        lines.append("")
        lines.append(f"Gate: **{'PASS' if unans['pass'] else 'FAIL'}**.")
    else:
        lines.append(f"**Not run.** {unans.get('reason', '')}")
    lines.append("")

    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--provider", default=None, help="anthropic (default) or bedrock")
    parser.add_argument("--model", default=None, help="override the provider's default model")
    parser.add_argument("--out-json", default=str(DEFAULT_JSON_OUT))
    parser.add_argument("--out-md", default=str(DEFAULT_MD_OUT))
    args = parser.parse_args(argv)

    provider = make_provider(name=args.provider, model=args.model)
    enabled = provider.is_enabled()

    if enabled:
        adv_result = adversarial_refusal.run(provider)
        ocr_result = ocr_proposals.run(provider)
        cite_result = citation_grounding.run(provider)
        unans_result = unanswerable.run(provider)
    else:
        print(f"warning: provider {provider.name!r} is not enabled; recording 'not run'")
        adv_result = adversarial_refusal.not_run()
        ocr_result = ocr_proposals.not_run()
        cite_result = citation_grounding.not_run()
        unans_result = unanswerable.not_run()

    leak_result = consent_leakage.run()  # always runs; needs no provider

    results = {
        "adversarial_refusal": adv_result,
        "ocr_proposals": ocr_result,
        "citation_grounding": cite_result,
        "consent_leakage": leak_result,
        "unanswerable_queries": unans_result,
    }

    out_json = Path(args.out_json)
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(json.dumps(results, indent=2, sort_keys=True) + "\n")

    out_md = Path(args.out_md)
    out_md.write_text(_render_markdown(results))

    print(f"wrote {out_json}")
    print(f"wrote {out_md}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
