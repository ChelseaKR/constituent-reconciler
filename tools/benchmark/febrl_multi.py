"""FEBRL datasets 1-3: widening the external benchmark beyond FEBRL4 (#68).

``tools/benchmark/febrl4.py`` already scores this project's matcher against a
third-party corpus and third-party ground truth (``dataset4a``/``dataset4b``,
two files, exactly one duplicate per original). The ``recordlinkage`` package
bundles three more FEBRL datasets at the same pinned commit, at three
increasing corruption levels, and this module gives them the same treatment:
fetched at run time, verified against recorded SHA-256 digests, converted
into a runnable recipe, and scored with the pipeline's own ``evaluate()``.
Nothing is vendored; the download directory is gitignored.

Datasets 1-3 differ from dataset4 in shape, not just size: each ships as ONE
file mixing originals (``rec-N-org``) and duplicates (``rec-N-dup-K``),
rather than two files, and an original can have more than one duplicate
(measured directly from the pinned files: dataset1 is always exactly one dup
per matched original, dataset2 up to five, dataset3 up to five with a much
larger matched share). Getting the grouping right matters here in a way it
did not for dataset4: the matcher runs in Splink ``dedupe_only`` mode
(``matching/splink_backend.py``), so two duplicates of the same person are
themselves a true pair the scorer must count, not only each duplicate against
the original. ``truth_clusters`` below groups every id sharing dsgen's
numeric person id into one cluster, survivor plus every duplicate, rather
than emitting one pair per duplicate the way a single-duplicate dataset
would; a dedicated test proves this against dataset3's own five-duplicate
case, where the naive per-pair derivation this module deliberately does not
use would silently under-count.

Existing/incoming split: the "-org" half of the file becomes ``existing.csv``
and the "-dup-*" half becomes ``incoming.csv``, the same role dataset4's two
separate files already play, so the recipe shape, the matcher configuration,
and the column mapping are identical across all four datasets.

Licensing and provenance match ``febrl4.py`` exactly: the Febrl project by
Peter Christen (Australian National University), redistributed inside the
``recordlinkage`` package by Jonathan de Bruin under a 3-clause BSD licence.
Declined for the same reason: a real-person corpus (the North Carolina voter
registry) was considered and is not used, because a public voter file is a
locating vector for exactly the people the DV policy pack protects.

Run one dataset with ``make eval-benchmark-multi DATASET=2``, or see
``docs/BENCHMARK.md`` for the committed numbers.
"""

