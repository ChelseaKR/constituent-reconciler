from tools.benchmark.febrl4 import UPSTREAM_BASE, UPSTREAM_COMMIT, compose_address


#: One entry per dataset this module supports. ``corruption_level`` is
#: FEBRL's own dsgen label, carried through to the report so a reader is not
#: left guessing why the three datasets score differently.
@dataclass(frozen=True)
class DatasetSpec:
    number: int
    filename: str
    sha256: str
    corruption_level: str


DATASETS: dict[int, DatasetSpec] = {
    1: DatasetSpec(
        1,
        "dataset1.csv",
        "637acf9db993a77cc49d479c7c53b739a748615f272a050ff973e8038b1b9cb6",
        "low",
    ),
    2: DatasetSpec(
        2,
        "dataset2.csv",
        "0c86efe0910769fbb13fb8c6fa01a7eedcd9a53a8ab8965b2946f87dcd7c4195",
        "medium",
    ),
    3: DatasetSpec(
        3,
        "dataset3.csv",
        "0e667330458ae88dd3d6b9cab39af4e7629a2fef98a810d0ea5f15e48220bdbf",
        "high",
    ),
}

_ORG_ID = re.compile(r"^rec-(\d+)-org$")
_DUP_ID = re.compile(r"^rec-(\d+)-dup-(\d+)$")

RECIPE = """\
# Generated by tools/benchmark/febrl_multi.py. Regenerate rather than edit.
#
# Same shape as the FEBRL4 recipe (tools/benchmark/febrl4.py): no email, no
# phone, no consent column in the source, so [mapping] is the whole of what
# the matcher gets to see.

[input]
existing = "existing.csv"
incoming = "incoming.csv"
id_column = "id"

[mapping]
first_name = "first_name"
last_name = "last_name"
dob = "dob"
address = "address"

[thresholds]
prior = 0.01
auto = 0.97
review = 0.80

[policy]
pack = "default"
"""


@dataclass(frozen=True)
class Prepared:
    out_dir: Path
    n_existing: int
    n_incoming: int
    n_true_pairs: int


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fetch(spec: DatasetSpec, raw_dir: Path, *, offline: bool = False) -> None:
    """Download the pinned source into ``raw_dir`` and verify its digest.

    Same fail-closed shape as ``febrl4.fetch``: a file present with the wrong
    digest is a hard error rather than silently scored, and ``--offline``
    refuses to reach the network at all.
    """

    raw_dir.mkdir(parents=True, exist_ok=True)
    target = raw_dir / spec.filename
    if target.is_file():
        actual = _digest(target)
        if actual == spec.sha256:
            return
        raise SystemExit(
            f"{target} does not match the pinned digest\n"
            f"  expected {spec.sha256}\n  actual   {actual}\n"
            "Delete it to re-download, or check the pin in tools/benchmark/febrl_multi.py."
        )
    if offline:
        raise SystemExit(f"--offline was given but {target} is missing")
    url = f"{UPSTREAM_BASE}/{spec.filename}"
    print(f"fetching {url}")
    with urllib.request.urlopen(url) as response:  # noqa: S310
        target.write_bytes(response.read())
    actual = _digest(target)
    if actual != spec.sha256:
        raise SystemExit(
            f"{spec.filename} failed digest verification after download\n"
            f"  expected {spec.sha256}\n  actual   {actual}"
        )


def _read(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return [dict(row) for row in csv.DictReader(handle, skipinitialspace=True)]


def _to_record(row: dict[str, str]) -> dict[str, str]:
    return {
        "id": row["rec_id"],
        "first_name": row.get("given_name", ""),
        "last_name": row.get("surname", ""),
        "dob": row.get("date_of_birth", ""),
        "address": compose_address(row),
    }


def _write_csv(path: Path, records: list[dict[str, str]]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(
            handle, fieldnames=["id", "first_name", "last_name", "dob", "address"]
        )
        writer.writeheader()
        writer.writerows(records)


def truth_clusters(record_ids: Iterable[str]) -> list[list[str]]:
    """Group every id sharing a numeric person id into one cluster.

    One file mixes ``rec-N-org`` and every ``rec-N-dup-K`` for that same
    ``N``. An original with no duplicate present, or a duplicate whose
    original is absent (both possible after a truncated or hand-edited
    input), contributes no cluster: a cluster must name a real survivor and
    at least one real duplicate. This is deliberately a full grouping by
    ``N``, not a series of ``(org, dup)`` pairs -- see the module docstring
    for why a dataset with more than one duplicate per original needs the
    distinction.
    """

    orgs: dict[str, str] = {}
    dups: dict[str, list[str]] = {}
    for rid in record_ids:
        org_match = _ORG_ID.match(rid)
        if org_match:
            orgs[org_match.group(1)] = rid
            continue
        dup_match = _DUP_ID.match(rid)
        if dup_match:
            dups.setdefault(dup_match.group(1), []).append(rid)

    clusters: list[list[str]] = []
    for number, org_id in orgs.items():
        members = dups.get(number)
        if not members:
            continue
        clusters.append(
            [f"existing:{org_id}"] + [f"incoming:{member}" for member in sorted(members)]
        )
    return clusters


def prepare(spec: DatasetSpec, raw_dir: Path, out_dir: Path) -> Prepared:
    """Convert the verified raw file into a runnable recipe plus ground truth."""

    rows = _read(raw_dir / spec.filename)
    existing_rows = [row for row in rows if _ORG_ID.match(row["rec_id"])]
    incoming_rows = [row for row in rows if _DUP_ID.match(row["rec_id"])]
    existing = [_to_record(row) for row in existing_rows]
    incoming = [_to_record(row) for row in incoming_rows]
    clusters = truth_clusters(row["rec_id"] for row in rows)

    out_dir.mkdir(parents=True, exist_ok=True)
    _write_csv(out_dir / "existing.csv", existing)
    _write_csv(out_dir / "incoming.csv", incoming)
    (out_dir / "recipe.toml").write_text(RECIPE, encoding="utf-8")
    # Matches evaluate.truth_pairs' own expansion: every cluster of size m
    # contributes C(m, 2) pairwise true duplicates, not m-1 -- a cluster with
    # more than one duplicate makes every duplicate a true pair of every
    # other duplicate too, not only of the survivor.
    n_true_pairs = sum(len(cluster) * (len(cluster) - 1) // 2 for cluster in clusters)
    (out_dir / "ground_truth.json").write_text(
        json.dumps(
            {
                "provenance": (
                    f"FEBRL dataset{spec.number} ({spec.corruption_level} corruption), "
                    f"fetched from the recordlinkage package at commit {UPSTREAM_COMMIT} "
                    "and verified against a pinned SHA-256 digest. Ground truth is not "
                    "authored here: it is derived from the upstream record ids, grouping "
                    "every id that shares one dsgen person number into one cluster. The "
                    "records are generated by FEBRL's dsgen from real Australian name and "
                    "address frequency tables, not collected from real people."
                ),
                "note": (
                    f"dataset{spec.number}: {len(existing)} originals, {len(incoming)} "
                    f"duplicates, {len(clusters)} matched persons, {n_true_pairs} true pairs "
                    "(clusters carry more than one duplicate per original when dsgen "
                    "generated more than one, so pairs exceed clusters)."
                ),
                "clusters": clusters,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    return Prepared(
        out_dir=out_dir,
        n_existing=len(existing),
        n_incoming=len(incoming),
        n_true_pairs=n_true_pairs,
    )


BENCHMARK_FIELDS = ("first_name", "last_name", "dob", "address")


def _population_rows(records: dict[str, Record]) -> list[tuple[str, int, int]]:
    rows = []
    for field_name in BENCHMARK_FIELDS:
        raw = sum(1 for r in records.values() if r.raw.get(field_name, "").strip())
        norm = sum(1 for r in records.values() if r.normalized.get(field_name, "").strip())
        rows.append((field_name, raw, norm))
    return rows


def threshold_sweep(
    pairs: Sequence[Pair],
    truth: Iterable[Iterable[str]],
    n_records: int,
    *,
    auto_thresholds: Sequence[float] = (0.80, 0.90, 0.95, 0.97, 0.99, 0.999),
    review_threshold: float = 0.80,
) -> list[tuple[float, EvalReport]]:
    """Re-band the same scored candidates at several auto thresholds.

    Cheap by construction: ``pairs`` already carries every candidate that
    survived blocking and scoring (``decisions.band_pairs``' own output,
    which is what ``RunResult.pairs`` is), at whatever probability the
    matcher assigned. Sweeping re-derives bands from those probabilities
    directly, so the expensive step (``matching.score_pairs``) runs once
    regardless of how many threshold points are swept.
    """

    truth_clusters_list = list(truth)
    scored = [(pair.left, pair.right, pair.probability) for pair in pairs]
    results: list[tuple[float, EvalReport]] = []
    for auto_threshold in auto_thresholds:
        rebanded = decisions.band_pairs(
            scored, auto_threshold=auto_threshold, review_threshold=review_threshold
        )
        report = evaluate(rebanded, truth_clusters_list, n_records=n_records)
        results.append((auto_threshold, report))
    return results


def render_sweep_table(sweep: list[tuple[float, EvalReport]]) -> list[str]:
    lines = [
        "",
        "### Threshold sweep",
        "",
        "Re-banding the same scored candidates at several auto-merge thresholds "
        "(review threshold held at 0.80). The matcher scores every candidate once; "
        "only the band boundary moves.",
        "",
        "| Auto threshold | Precision (auto) | Recall (auto) | F1 (auto) | False merges | "
        "Auto pairs |",
        "|---|---|---|---|---|---|",
    ]
    for threshold, report in sweep:
        lines.append(
            f"| {threshold:.3f} | {report.precision_auto * 100:.1f}% "
            f"| {report.recall_auto * 100:.1f}% | {report.f1_auto * 100:.1f}% "
            f"| {report.false_merges} | {report.n_auto} |"
        )
    return lines


def run(
    dataset: int,
    out_dir: Path,
    *,
    gate: float,
    offline: bool,
    raw_dir: Path | None = None,
) -> tuple[str, EvalReport, bool]:
    """Prepare, run, score, and sweep one FEBRL dataset. Mirrors ``run_eval.run``."""

    spec = DATASETS[dataset]
    raw = raw_dir or (out_dir / "raw")
    fetch(spec, raw, offline=offline)
    prepared = prepare(spec, raw, out_dir)

    recipe = load_recipe(str(out_dir / "recipe.toml"))
    result = pipeline.run(recipe)

    truth = json.loads((out_dir / "ground_truth.json").read_text(encoding="utf-8"))
    report = evaluate(result.pairs, truth["clusters"], n_records=len(result.records))

    if prepared.n_true_pairs != report.n_true_pairs:
        raise SystemExit(
            f"ground-truth mismatch: prepared {prepared.n_true_pairs} pairs but "
            f"scored {report.n_true_pairs}; {out_dir} holds a stale truth file"
        )

    markdown = render_eval_markdown(
        report,
        dataset=f"FEBRL dataset{dataset} ({spec.corruption_level} corruption)",
        gate_threshold=gate,
        provenance=truth.get("provenance"),
        generator="make eval-benchmark-multi",
        field_judge_ran=False,
    )
    lines = [
        "",
        "## Flow-through evidence",
        "",
        "| Source file | SHA-256 |",
        "|-------------|---------|",
        f"| `{spec.filename}` | `{_digest(raw / spec.filename)}` |",
        "",
        f"Upstream commit `{UPSTREAM_COMMIT}`. Records ingested: {len(result.records)}. "
        f"Matched persons (ground-truth clusters): {len(truth['clusters'])}. "
        f"Ground-truth pairs derived from upstream record ids: {report.n_true_pairs}.",
        "",
        "### Field population after normalization",
        "",
        "| Canonical field | Raw non-empty | Normalized non-empty | Dropped |",
        "|-----------------|---------------|----------------------|---------|",
    ]
    for field_name, raw_count, norm_count in _population_rows(result.records):
        lines.append(f"| {field_name} | {raw_count} | {norm_count} | {raw_count - norm_count} |")

    sweep = threshold_sweep(result.pairs, truth["clusters"], len(result.records))
    lines += render_sweep_table(sweep)

    full = markdown + "\n".join(lines) + "\n"
    return full, report, report.false_merge_rate <= gate


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", type=int, choices=sorted(DATASETS), required=True)
    parser.add_argument("--out-dir", type=Path, default=None)
    parser.add_argument("--report-out", type=Path, default=None)
    parser.add_argument("--gate", type=float, default=0.01)
    parser.add_argument("--offline", action="store_true")
    args = parser.parse_args(argv)

    out_dir = args.out_dir or Path(f"benchmarks/febrl{args.dataset}")
    report_out = args.report_out or Path(f"eval/febrl{args.dataset}-report.md")

    markdown, report, gate_pass = run(args.dataset, out_dir, gate=args.gate, offline=args.offline)
    report_out.parent.mkdir(parents=True, exist_ok=True)
    report_out.write_text(markdown, encoding="utf-8")
    print(f"wrote benchmark eval report: {report_out}")
    print(
        f"false-merge rate {report.false_merge_rate * 100:.2f}% "
        f"({report.false_merges}/{report.n_auto}), gate {'PASS' if gate_pass else 'FAIL'}"
    )
    print(
        f"coverage precision {report.precision_coverage * 100:.1f}%, "
        f"recall {report.recall_coverage * 100:.1f}%, F1 {report.f1_coverage * 100:.1f}%"
    )
    return 0 if gate_pass else 1


if __name__ == "__main__":
    raise SystemExit(main())
