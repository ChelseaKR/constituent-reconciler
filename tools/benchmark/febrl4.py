"""Prepare the FEBRL4 record-linkage benchmark as a recipe this pipeline can run.

Every other eval in this repository scores the matcher against fixtures this
repository also wrote. That is circular: the corpus, the error channels, and the
ground truth all come from the same hand, so a favourable number partly measures
the fixture author's imagination. FEBRL4 is the opposite arrangement. The corpus,
the corruptions, and the ground truth are all third-party and published, and this
repository only supplies the matcher.

What FEBRL4 is, stated plainly so no reader has to infer it:

* Two files of 5,000 person records each, ``dataset4a`` (originals) and
  ``dataset4b`` (one corrupted duplicate of each original). Exactly 5,000 true
  pairs, one per original, and no duplicates within either file.
* Ground truth is carried in the record ids, not asserted by us: ``rec-N-org`` in
  the A file is the same person as ``rec-N-dup-0`` in the B file. This module
  derives the truth clusters from those ids and nothing else.
* The records are **generated**, not collected. FEBRL's ``dsgen`` samples names,
  addresses and dates from real Australian frequency tables and then applies
  typographic, phonetic and field-swap corruptions. So the *data* is synthetic
  while the *benchmark* is external: difficulty and ground truth were both fixed
  by someone else, years before this repository existed.

Why not a corpus of real people. The obvious upgrade is a benchmark built from
real person records, and the standard one is the North Carolina voter registry
(the Leipzig NCVR sets). This project declines it. A public voter file is a
recognised locating vector for exactly the people the DV policy pack exists to
protect, and pulling one onto a contributor's disk to make a portfolio number
look better is not a trade this repository should make. That constraint is not an
accident of this benchmark; it is the reason open person-linkage corpora with
real ground truth are rare at all. docs/BENCHMARK.md records the decision.

Licensing and provenance. The FEBRL datasets originate with the Febrl project by
Peter Christen (Australian National University) and are redistributed inside the
``recordlinkage`` Python package by Jonathan de Bruin under a 3-clause BSD
licence. Nothing is vendored here: the files are fetched at run time from a
pinned commit and verified against the SHA-256 digests below, and the download
directory is gitignored so no benchmark data ever enters this repository.

Run it with ``make eval-benchmark``.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
import sys
import urllib.request
from dataclasses import dataclass
from pathlib import Path

#: Pinned upstream revision. A tag would be a moving reference if it were ever
#: re-cut; the commit sha cannot be. recordlinkage v0.16.
UPSTREAM_COMMIT = "b93d97641952f8c85106be5794ca93b1f1298fbc"
UPSTREAM_BASE = (
    f"https://raw.githubusercontent.com/J535D165/recordlinkage/{UPSTREAM_COMMIT}"
    "/recordlinkage/datasets/febrl"
)

#: SHA-256 of each source file at UPSTREAM_COMMIT. A mismatch aborts rather than
#: scoring whatever arrived, so a silently changed upstream cannot quietly move
#: the published numbers.
SOURCES: dict[str, str] = {
    "dataset4a.csv": "07c7cb3f0a8d88180e80317f2a60499dee4e8324a44c38059f4e7fed0a8b4488",
    "dataset4b.csv": "2eed76c99fa2237be3ec013a123427926d4158abcb3a8f65874d6c7f1358cf2c",
}

#: ``rec-<n>-org`` in the A file pairs with ``rec-<n>-dup-<k>`` in the B file.
_ORG_ID = re.compile(r"^rec-(\d+)-org$")
_DUP_ID = re.compile(r"^rec-(\d+)-dup-(\d+)$")

RECIPE = """\
# Generated by tools/benchmark/febrl4.py. Regenerate rather than edit.
#
# FEBRL4 carries no email, no phone and no consent column, so the [mapping]
# below is the whole of what the matcher gets to see: two name fields, a date of
# birth, and a composed address. There is no [consent] section because inventing
# a consent value the source never recorded would make the export gate score
# against fabricated input.

[input]
existing = "existing.csv"
incoming = "incoming.csv"
id_column = "id"

[mapping]
first_name = "first_name"
last_name = "last_name"
dob = "dob"
address = "address"

[thresholds]
prior = 0.01
auto = 0.97
review = 0.80

[policy]
pack = "default"
"""


@dataclass(frozen=True)
class Prepared:
    """What ``prepare`` wrote, for the caller to report on."""

    out_dir: Path
    n_existing: int
    n_incoming: int
    n_true_pairs: int


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fetch(raw_dir: Path, *, offline: bool = False) -> None:
    """Download each pinned source into ``raw_dir`` and verify its digest.

    A file already present with the right digest is left alone, so repeat runs
    do not re-download and ``--offline`` works against a warm directory. A file
    present with the *wrong* digest is a hard error either way: it is either a
    truncated download or a different corpus, and both would silently change the
    numbers.
    """

    raw_dir.mkdir(parents=True, exist_ok=True)
    for name, expected in SOURCES.items():
        target = raw_dir / name
        if target.is_file():
            actual = _digest(target)
            if actual == expected:
                continue
            raise SystemExit(
                f"{target} does not match the pinned digest\n"
                f"  expected {expected}\n  actual   {actual}\n"
                "Delete it to re-download, or check the pin in tools/benchmark/febrl4.py."
            )
        if offline:
            raise SystemExit(f"--offline was given but {target} is missing")
        url = f"{UPSTREAM_BASE}/{name}"
        print(f"fetching {url}")
        # S310: the URL is built from a constant base and a key of the SOURCES
        # table, so the scheme is always https and never caller-controlled.
        with urllib.request.urlopen(url) as response:  # noqa: S310
            target.write_bytes(response.read())
        actual = _digest(target)
        if actual != expected:
            raise SystemExit(
                f"{name} failed digest verification after download\n"
                f"  expected {expected}\n  actual   {actual}"
            )


def _read(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        # FEBRL's header is comma-space separated; skipinitialspace keeps the
        # field names from carrying a leading blank.
        return [dict(row) for row in csv.DictReader(handle, skipinitialspace=True)]


def compose_address(row: dict[str, str]) -> str:
    """Join FEBRL's split address columns into one line for the standardizer.

    ``address_2`` is a locality or building name rather than a second street
    line, so it is placed after the street and before the suburb. Empty parts are
    dropped instead of leaving separator runs, because a normalized address of
    ``", , 4223"`` compares as a populated field when it carries no information.
    """

    street = " ".join(
        part for part in (row.get("street_number", ""), row.get("address_1", "")) if part.strip()
    )
    tail = " ".join(
        part
        for part in (row.get("suburb", ""), row.get("state", ""), row.get("postcode", ""))
        if part.strip()
    )
    parts = [part for part in (street, row.get("address_2", "").strip(), tail) if part.strip()]
    return ", ".join(parts)


def _to_records(rows: list[dict[str, str]]) -> list[dict[str, str]]:
    return [
        {
            "id": row["rec_id"],
            "first_name": row.get("given_name", ""),
            "last_name": row.get("surname", ""),
            # Passed through in FEBRL's native YYYYMMDD. Converting it here would
            # hide whether the pipeline's own normalizer handles the format, and
            # that is one of the things this benchmark is meant to find out.
            "dob": row.get("date_of_birth", ""),
            "address": compose_address(row),
        }
        for row in rows
    ]


def _write_csv(path: Path, records: list[dict[str, str]]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(
            handle, fieldnames=["id", "first_name", "last_name", "dob", "address"]
        )
        writer.writeheader()
        writer.writerows(records)


def truth_clusters(
    existing: list[dict[str, str]], incoming: list[dict[str, str]]
) -> list[list[str]]:
    """Derive ground-truth clusters from FEBRL's record ids.

    The pipeline namespaces every record id by its source file, so the cluster
    members must be written the same way (``existing:rec-1070-org``). Only
    originals that actually have a duplicate present are emitted, so a truncated
    input produces fewer pairs rather than clusters naming absent records.
    """

    originals = {}
    for row in existing:
        match = _ORG_ID.match(row["id"])
        if match:
            originals[match.group(1)] = row["id"]

    clusters: list[list[str]] = []
    for row in incoming:
        match = _DUP_ID.match(row["id"])
        if not match:
            continue
        original = originals.get(match.group(1))
        if original is not None:
            clusters.append([f"existing:{original}", f"incoming:{row['id']}"])
    return clusters


def prepare(raw_dir: Path, out_dir: Path) -> Prepared:
    """Convert the verified raw files into a runnable recipe plus ground truth."""

    existing = _to_records(_read(raw_dir / "dataset4a.csv"))
    incoming = _to_records(_read(raw_dir / "dataset4b.csv"))
    clusters = truth_clusters(existing, incoming)

    out_dir.mkdir(parents=True, exist_ok=True)
    _write_csv(out_dir / "existing.csv", existing)
    _write_csv(out_dir / "incoming.csv", incoming)
    (out_dir / "recipe.toml").write_text(RECIPE, encoding="utf-8")
    (out_dir / "ground_truth.json").write_text(
        json.dumps(
            {
                "provenance": (
                    "FEBRL4 (dataset4a/dataset4b), fetched from the recordlinkage package at "
                    f"commit {UPSTREAM_COMMIT} and verified against pinned SHA-256 digests. "
                    "Ground truth is not authored here: it is derived from the upstream record "
                    "ids, where rec-N-org and rec-N-dup-0 are the same person. The records are "
                    "generated by FEBRL's dsgen from real Australian name and address frequency "
                    "tables, not collected from real people."
                ),
                "note": (
                    "Each cluster is one original and its single corrupted duplicate. Ids are "
                    "namespaced by source, matching how the pipeline labels records."
                ),
                "clusters": clusters,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    return Prepared(
        out_dir=out_dir,
        n_existing=len(existing),
        n_incoming=len(incoming),
        n_true_pairs=len(clusters),
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--out-dir",
        default="benchmarks/febrl4",
        help="where to write the runnable recipe (default: benchmarks/febrl4)",
    )
    parser.add_argument(
        "--raw-dir",
        default=None,
        help="where to cache the downloaded sources (default: <out-dir>/raw)",
    )
    parser.add_argument(
        "--offline",
        action="store_true",
        help="fail instead of downloading if the sources are not already cached",
    )
    args = parser.parse_args(argv)

    out_dir = Path(args.out_dir)
    raw_dir = Path(args.raw_dir) if args.raw_dir else out_dir / "raw"

    fetch(raw_dir, offline=args.offline)
    prepared = prepare(raw_dir, out_dir)
    print(
        f"prepared {prepared.n_existing} existing and {prepared.n_incoming} incoming records "
        f"with {prepared.n_true_pairs} ground-truth pairs in {prepared.out_dir}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
